def _hostname(url: str) -> str:
    """
    ALLOWED_HOSTS wants a bare hostname.

    FRONTEND_URL is a full URL, and putting it in ALLOWED_HOSTS unchanged
    never matches a Host header, so the entry did nothing.
    """

    from urllib.parse import urlparse

    parsed = urlparse(url if "//" in url else f"//{url}")

    return (parsed.hostname or "").strip()


ALLOWED_HOSTS = [
    host
    for host in [
        "localhost",
        "127.0.0.1",
        _hostname(FRONTEND_URL),
        *[
            entry.strip()
            for entry in config("ALLOWED_HOSTS", default="").split(",")
        ],
    ]
    if host
]


